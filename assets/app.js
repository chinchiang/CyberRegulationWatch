const state = {
  language: localStorage.getItem("crw-language") || "zh-Hant",
  manifest: null
};

const dateFormatter = (iso, language = state.language) =>
  new Intl.DateTimeFormat(language === "en" ? "en-GB" : "zh-TW", {
    year: "numeric",
    month: "short",
    day: "2-digit",
    timeZone: "Asia/Taipei"
  }).format(new Date(iso));

function t(key) {
  return translations[state.language][key] || translations["zh-Hant"][key] || key;
}

function applyLanguage(language) {
  state.language = language;
  localStorage.setItem("crw-language", language);
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.textContent = translations[language][key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (translations[language][key]) element.placeholder = translations[language][key];
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });

  if (state.manifest) render(state.manifest);
}

function safeText(value) {
  const node = document.createElement("span");
  node.textContent = String(value ?? "");
  return node.innerHTML;
}

function reportUrl(report) {
  return `report.html?id=${encodeURIComponent(report.id)}`;
}

function normalizeCounts(report) {
  return ["P0", "P1", "P2", "P3"].reduce((result, priority) => {
    result[priority] = Number(report.priorityCounts?.[priority] || 0);
    return result;
  }, {});
}

function renderLatest(report) {
  const panel = document.getElementById("latest-panel");
  if (!report) return;
  const counts = normalizeCounts(report);
  const maxCount = Math.max(1, ...Object.values(counts));
  const statusKey = report.status === "material-change" ? "statusMaterial" : "statusNoMaterial";
  const bars = ["P0", "P1", "P2", "P3"].map((priority, index) => {
    const colors = ["#f2298a", "#ff7a1a", "#7447ff", "#1677ff"];
    const width = Math.round((counts[priority] / maxCount) * 100);
    return `
      <div class="priority-stat">
        <b>${priority}</b>
        <i style="--bar:${width}%;--bar-color:${colors[index]}"></i>
        <strong>${counts[priority]}</strong>
      </div>`;
  }).join("");

  panel.innerHTML = `
    <div class="latest-report">
      <div>
        <span class="status-label status-${safeText(report.status)}">${safeText(t(statusKey))}</span>
        <h3>${safeText(report.title)}</h3>
        <p>${safeText(report.executiveSummary)}</p>
        <div class="latest-actions">
          <a class="button button-primary" href="${reportUrl(report)}">${safeText(t("readBrief"))}<span aria-hidden="true">↗</span></a>
          <span class="button button-ghost">${safeText(dateFormatter(report.publishedAt))}</span>
        </div>
      </div>
      <div class="priority-row">${bars}</div>
    </div>`;
}

function renderReports(reports) {
  const query = document.getElementById("search").value.trim().toLocaleLowerCase();
  const scope = document.getElementById("scope-filter").value;
  const priority = document.getElementById("priority-filter").value;
  const status = document.getElementById("status-filter").value;

  const filtered = reports.filter((report) => {
    const haystack = [
      report.title,
      report.executiveSummary,
      ...(report.scopes || []),
      ...(report.tags || []),
      ...(report.decisions || []),
      ...(report.deadlines || [])
    ].join(" ").toLocaleLowerCase();

    return (!query || haystack.includes(query))
      && (!scope || (report.scopes || []).includes(scope))
      && (!priority || Number(report.priorityCounts?.[priority] || 0) > 0)
      && (!status || report.status === status);
  });

  const grid = document.getElementById("report-grid");
  const count = document.getElementById("result-count");

  if (!reports.length) {
    grid.innerHTML = `<div class="empty-state"><div><strong>${safeText(t("emptyTitle"))}</strong>${safeText(t("emptyText"))}</div></div>`;
    count.textContent = "";
    return;
  }

  if (!filtered.length) {
    grid.innerHTML = `<div class="empty-state"><div><strong>${safeText(t("noResultsTitle"))}</strong>${safeText(t("noResultsText"))}</div></div>`;
    count.textContent = `0 / ${reports.length} ${t("reportUnit")}`;
    return;
  }

  grid.innerHTML = filtered.map((report) => {
    const statusKey = report.status === "material-change" ? "statusMaterial" : "statusNoMaterial";
    const tags = [...(report.scopes || []), ...(report.tags || [])].slice(0, 5);
    return `
      <article class="report-card">
        <div class="report-card-top">
          <span class="report-date">${safeText(dateFormatter(report.publishedAt))}</span>
          <span class="status-label status-${safeText(report.status)}">${safeText(t(statusKey))}</span>
        </div>
        <h3>${safeText(report.title)}</h3>
        <p>${safeText(report.executiveSummary)}</p>
        <div class="tag-row">${tags.map((tag) => `<span class="tag">${safeText(tag)}</span>`).join("")}</div>
        <a class="report-link" href="${reportUrl(report)}"><span>${safeText(t("readBrief"))}</span><span aria-hidden="true">↗</span></a>
      </article>`;
  }).join("");

  count.textContent = `${filtered.length} / ${reports.length} ${t("reportUnit")}`;
}

function renderSchedule(manifest) {
  const nextRun = new Date(manifest.nextScheduledRun);
  document.getElementById("next-run-date").textContent = new Intl.DateTimeFormat(
    state.language === "en" ? "en-GB" : "zh-TW",
    { year: "numeric", month: "2-digit", day: "2-digit", timeZone: "Asia/Taipei" }
  ).format(nextRun);
  document.getElementById("next-run-time").textContent = state.language === "en"
    ? "MON · 08:00 TPE"
    : "週一 · 08:00 臺北";

  const taipeiParts = Object.fromEntries(
    new Intl.DateTimeFormat("en-CA", {
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      timeZone: "Asia/Taipei"
    }).formatToParts(new Date())
      .filter((part) => part.type !== "literal")
      .map((part) => [part.type, Number(part.value)])
  );
  const [craYear, craMonth, craDay] = manifest.milestones.craArticle14
    .slice(0, 10)
    .split("-")
    .map(Number);
  const todayCalendar = Date.UTC(taipeiParts.year, taipeiParts.month - 1, taipeiParts.day);
  const craCalendar = Date.UTC(craYear, craMonth - 1, craDay);
  const days = Math.max(0, Math.ceil((craCalendar - todayCalendar) / 86400000));
  document.getElementById("cra-days").textContent = String(days).padStart(2, "0");
}

function render(manifest) {
  const reports = [...manifest.reports].sort((a, b) => new Date(b.publishedAt) - new Date(a.publishedAt));
  document.getElementById("report-count").textContent = String(reports.length).padStart(2, "0");
  const updated = document.getElementById("last-updated");
  updated.textContent = manifest.lastUpdated
    ? `${t("lastUpdatePrefix")} ${dateFormatter(manifest.lastUpdated)}`
    : t("awaitingFirst");
  renderSchedule(manifest);
  renderLatest(reports[0]);
  renderReports(reports);
}

async function loadManifest() {
  try {
    const response = await fetch("data/reports.json", { cache: "no-store" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    state.manifest = await response.json();
    render(state.manifest);
  } catch (error) {
    document.getElementById("report-grid").innerHTML =
      `<div class="empty-state"><div><strong>Manifest unavailable</strong>${safeText(error.message)}</div></div>`;
  }
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

document.querySelectorAll("#filters input, #filters select").forEach((field) => {
  field.addEventListener("input", () => {
    if (state.manifest) renderReports(state.manifest.reports);
  });
});

const mobileNavLinks = [...document.querySelectorAll(".mobile-dock a")];
const mobileSections = mobileNavLinks
  .map((link) => document.getElementById(link.dataset.mobileTarget))
  .filter(Boolean);

if ("IntersectionObserver" in window && mobileSections.length) {
  const mobileObserver = new IntersectionObserver((entries) => {
    const visible = entries
      .filter((entry) => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
    if (!visible) return;
    mobileNavLinks.forEach((link) => {
      link.classList.toggle("is-active", link.dataset.mobileTarget === visible.target.id);
    });
  }, { rootMargin: "-20% 0px -65% 0px", threshold: [0, 0.1, 0.4] });
  mobileSections.forEach((section) => mobileObserver.observe(section));
}

mobileNavLinks.forEach((link) => {
  link.addEventListener("click", () => {
    mobileNavLinks.forEach((item) => item.classList.toggle("is-active", item === link));
  });
});

applyLanguage(state.language);
loadManifest();

